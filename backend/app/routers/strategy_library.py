@router.get("")
def get_strategy_library(
    category: Optional[str] = Query(None, description="Filter by category (e.g. Momentum)"),
    asset_class: Optional[str] = Query(None, description="Filter by asset class (stocks, crypto, options, multi)"),
    time_horizon: Optional[str] = Query(None, description="Filter by time horizon (intraday, swing, position, long_term)"),
    difficulty: Optional[str] = Query(None, description="Filter by difficulty (beginner, intermediate, advanced)"),
    search: Optional[str] = Query(None, description="Text search across display_name, tagline, and category"),
    suggested_bot: Optional[str] = Query(None, description="Filter by suggested bot profile name"),
    sort: str = Query("sharpe", description="Sort order: sharpe | alphabetical | top_pick"),
    is_top_pick: Optional[bool] = Query(None, description="Filter to top picks only"),
    current_user: User = Depends(get_current_user),
) -> Dict[str, Any]:
    """Return the full strategy catalog with optional filtering and sorting."""

    results = list(CATALOG)

    # ── Filters ──────────────────────────────────────────────────────────────
    if category is not None:
        results = [s for s in results if s.get("category", "").lower() == category.lower()]

    if asset_class is not None:
        results = [s for s in results if s.get("asset_class", "").lower() == asset_class.lower()]

    if time_horizon is not None:
        results = [s for s in results if s.get("time_horizon", "").lower() == time_horizon.lower()]

    if difficulty is not None:
        results = [s for s in results if s.get("difficulty", "").lower() == difficulty.lower()]

    if suggested_bot is not None:
        results = [s for s in results if s.get("suggested_bot", "").lower() == suggested_bot.lower()]

    if is_top_pick is not None:
        results = [s for s in results if s.get("is_top_pick") == is_top_pick]

    if search:
        q = search.lower()
        results = [
            s for s in results
            if q in (s.get("display_name") or "").lower()
            or q in (s.get("tagline") or "").lower()
            or q in (s.get("category") or "").lower()
            or q in (s.get("description_md") or "").lower()
        ]

    # ── Sort ─────────────────────────────────────────────────────────────────
    if sort == "alphabetical":
        results.sort(key=lambda s: (s.get("display_name") or "").lower())
    elif sort == "top_pick":
        results.sort(
            key=lambda s: (
                not s.get("is_top_pick", False),        # True (top picks) first
                -(s.get("published_sharpe") or 0.0),   # then by sharpe desc
            )
        )
    else:  # default: sharpe
        results.sort(key=lambda s: -(s.get("published_sharpe") or 0.0))

    # ── Category counts (on the un-filtered full catalog) ────────────────────
    category_counts: Dict[str, int] = {}
    for s in CATALOG:
        cat = s.get("category") or "Uncategorized"
        category_counts[cat] = category_counts.get(cat, 0) + 1

    return {
        "strategies": results,
        "total": len(results),
        "categories": category_counts,
    }
